SET SESSION TRANSACTION ISOLATION LEVEL READ UNCOMMITTED;

-- Tab 1
SELECT DISTINCT
    CONCAT(P.PDVENDOR, P.PDNUMBER, P.PDSTORE) AS `UID`,
    P.PDVENDOR,
    P.PDNUMBER,
    P.PDSTORE,
    P.PDDESCRIP,
    P.PDINVMEMO,
    P.PDACTCOST,
    D.TPDHSPRIC1,
    ROUND(D.TPDHSPRIC1 * 0.96, 2) AS `New ACT Cost`,
    ROUND(P.PDACTCOST - (D.TPDHSPRIC1 * 0.96), 2) AS `Change`
FROM DTA273.TMPROD P
INNER JOIN KMTDTA.STORES S
    ON P.PDSTORE = S.STORENUM
   AND S.ACTIVE = 'Y'
LEFT JOIN DTA273.TMPDHS D
    ON D.TPDHSNBPD = P.PDNUMBER
WHERE P.PDDELETE = 'A'
  AND P.PDFLGUSR6 = 'S'
  AND P.PDINVMEMO > 0
  AND (P.PDACTCOST - D.TPDHSPRIC1) > 0;


