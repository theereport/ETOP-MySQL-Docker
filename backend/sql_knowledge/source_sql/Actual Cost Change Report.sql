    ROUND(P.PDINVMEMO * (P.PDREPLCOST - P.PDACTCOST), 2) AS `Change`
FROM DTA273.TMPROD P
INNER JOIN KMTDTA.STORES S
    ON P.PDSTORE = S.STORENUM
   AND S.ACTIVE = 'Y'
WHERE P.PDDELETE = 'A'
  AND P.PDFLGUSR6 <> 'S'
  AND P.PDACTCOST <> 0
  AND P.PDCLASS BETWEEN '01' AND '21'
  AND (P.PDREPLCOST - P.PDACTCOST) / P.PDREPLCOST >= .03;